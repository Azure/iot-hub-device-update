#!/usr/bin/env python3
"""
Extension Result Code Generator

Generic generator for extension result code headers.
Generates C header files containing result code definitions for ADU extensions.
The result codes follow the ADUC extended result code format:
    32-bit value = | Facility (4 bits) | Component (8 bits) | Result (20 bits) |

Usage:
    extension_result_code_generator.py -j <json_path> -o <output_path>
    
Example:
    extension_result_code_generator.py \\
        -j swupdate_handler_result_codes.json \\
        -o inc/aduc/swupdate_handler_result_codes.h
"""

import argparse
import json
import os
import sys
from datetime import datetime
from pathlib import Path


def calculate_erc(facility_code: int, component_code: int, result_value: int) -> int:
    """
    Calculate the full Extended Result Code (ERC) from components.
    
    Format: 0xFCCRRRRR where:
        F = Facility (4 bits, max 15)
        CC = Component (8 bits, max 255)  
        RRRRR = Result (20 bits, max 1048575)
    """
    if facility_code > 0xF:
        raise ValueError(f"Facility code {facility_code} exceeds max value 15")
    if component_code > 0xFF:
        raise ValueError(f"Component code {component_code} exceeds max value 255")
    if result_value > 0xFFFFF:
        raise ValueError(f"Result value {result_value} exceeds max value 1048575")
    
    return (facility_code << 28) | (component_code << 20) | result_value


def sanitize_name(name: str) -> str:
    """Convert a name to uppercase snake case for C macros."""
    return name.upper().replace('-', '_').replace(' ', '_')


def generate_header(json_path: str, output_path: str) -> None:
    """Generate C header file from JSON result codes definition."""
    
    # Read JSON file
    with open(json_path, 'r') as f:
        data = json.load(f)
    
    facility = data['facility']
    component = data['component']
    result_codes = data['result_codes']
    
    # Derive names from component name for flexibility
    component_name_upper = sanitize_name(component['name'])
    component_name_lower = component['name'].lower().replace('_', '_').replace(' ', '_')
    
    # Generate header guard and file name from component name
    header_guard = f"ADUC_{component_name_upper}_RESULT_CODES_H"
    header_filename = f"{component_name_lower}_result_codes.h"
    
    # Generate macro prefix from component name
    facility_macro = f"ADUC_FACILITY_CODE_{component_name_upper}"
    component_macro = f"ADUC_COMPONENT_CODE_{component_name_upper}"
    helper_macro = f"MAKE_{component_name_upper}_ERC"
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    json_filename = Path(json_path).name
    
    lines = [
        "/**",
        f" * @file {header_filename}",
        f" * @brief Extended Result Codes for {component['name']}",
        " *",
        f" * Auto-generated on {timestamp}",
        " * DO NOT EDIT THIS FILE MANUALLY",
        " *",
        f" * Generated from: {json_filename}",
        " * Generator: extension_result_code_generator.py",
        " *",
        " * Extended Result Code Format (32-bit):",
        " *   Bits 31-28: Facility Code",
        " *   Bits 27-20: Component Code", 
        " *   Bits 19-0:  Result Code",
        " */",
        "",
        f"#ifndef {header_guard}",
        f"#define {header_guard}",
        "",
        "/**",
        f" * Facility: {facility['name']} (0x{facility['code']:X})",
        f" * {facility['doc_string']}",
        " */",
        f"#define {facility_macro} 0x{facility['code']:X}",
        "",
        "/**",
        f" * Component: {component['name']} (0x{component['code']:02X})",
        f" * {component['doc_string']}",
        " */",
        f"#define {component_macro} 0x{component['code']:02X}",
        "",
        "/**",
        " * Extended Result Codes",
        f" * Format: 0x{facility['code']:X}{component['code']:02X}RRRRR",
        f" *   F = Facility (0x{facility['code']:X})",
        f" *   CC = Component (0x{component['code']:02X})",
        " *   RRRRR = Result code",
        " */",
        ""
    ]
    
    # Add result code definitions
    for rc in result_codes:
        erc = calculate_erc(facility['code'], component['code'], rc['value'])
        lines.append(f"/** {rc['description']} | {rc['name']} = {erc} (0x{erc:08X}) */")
        lines.append(f"#define {rc['name']} 0x{erc:08X}")
        lines.append("")
    
    # Add helper macro
    lines.extend([
        "/**",
        f" * Helper macro to create {component['name']} extended result codes",
        " * @param result_value The result code value (0-1048575)",
        " */",
        f"#define {helper_macro}(result_value) \\",
        f"    (({facility_macro} << 28) | \\",
        f"     ({component_macro} << 20) | \\",
        "     (result_value))",
        "",
        f"#endif // {header_guard}",
        ""
    ])
    
    # Write header file (smart-write: only update if changed)
    content = '\n'.join(lines)
    should_write = True
    
    if os.path.exists(output_path):
        try:
            with open(output_path, 'r') as existing_file:
                if existing_file.read() == content:
                    print(f"No changes detected in {output_path}, skipping write")
                    should_write = False
        except Exception as e:
            print(f"Could not read existing file for comparison: {e}")
    
    if should_write:
        output_dir = Path(output_path).parent
        output_dir.mkdir(parents=True, exist_ok=True)
        
        with open(output_path, 'w') as f:
            f.write(content)
        
        print(f"Generated: {output_path}")
    
    print(f"  Facility: {facility['name']} (0x{facility['code']:X})")
    print(f"  Component: {component['name']} (0x{component['code']:02X})")
    print(f"  Result codes: {len(result_codes)}")


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description='Generate extension result code header from JSON definition',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__)
    
    parser.add_argument('-j', '--json-file', required=True,
                        help='Path to the JSON file defining result codes')
    parser.add_argument('-o', '--output', required=True,
                        help='Path where the header file should be generated')
    
    args = parser.parse_args()
    
    json_path = Path(args.json_file)
    output_path = Path(args.output)
    
    if not json_path.exists():
        print(f"ERROR: JSON file not found: {json_path}", file=sys.stderr)
        return 1
    
    if not json_path.is_file():
        print(f"ERROR: JSON path is not a file: {json_path}", file=sys.stderr)
        return 1
    
    try:
        generate_header(str(json_path), str(output_path))
        return 0
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        import traceback
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
