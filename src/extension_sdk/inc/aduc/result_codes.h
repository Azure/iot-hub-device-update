/**
 * @file result_codes.h
 * @brief Comprehensive Result Code (RC) registry for ADU Gen2 agent.
 *
 * Layout: [facility:8][category:8][specific:16]
 *
 * Convention:
 * - RC = Result Code (the 32-bit ADUC_Result2.code value)
 * - ERC = Extended Result Code (for backward compat with Gen1 reporting)
 * - Each code has format: ADUC_RC_{FACILITY}_{CATEGORY}_{DESCRIPTION}
 *
 * @copyright Copyright (c) Microsoft Corporation.
 * Licensed under the MIT License.
 */
