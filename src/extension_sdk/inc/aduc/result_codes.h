/* ═══════════════════════════════════════════════════════════════════════════
 * Helper macros — extract fields from a result code
 * ═══════════════════════════════════════════════════════════════════════════ */

#define ADUC_RC_GET_FACILITY(rc)  (((rc).code >> 24) & 0xFF)
#define ADUC_RC_GET_CATEGORY(rc)  (((rc).code >> 16) & 0xFF)
#define ADUC_RC_GET_SPECIFIC(rc)  ((rc).code & 0xFFFF)

